import { Student, Intervention, Role } from '@/types';

export function downloadRoleReport(
  role: Role,
  student?: Student | null,
  allStudents: Student[] = [],
  interventions: Intervention[] = []
) {
  if (typeof window === 'undefined') return;

  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    alert('Please allow popups to download the official report.');
    return;
  }

  let title = 'Kalvikkan AI Academic Report';
  let bodyContent = '';

  if (role === 'student' && student) {
    title = `Academic Performance Report - ${student.name} (${student.emis})`;
    bodyContent = `
      <div class="header">
        <div class="logo-box">
          <div class="logo-title">கல்விக்கண் (KALVIKKAN)</div>
          <div class="logo-sub">AI-Powered Early Warning & Student Success Platform</div>
          <div class="tagline">கற்றல் | முன்னேற்றம் | சிறந்த எதிர்காலம்</div>
        </div>
        <div class="report-meta">
          <div><strong>Date:</strong> ${new Date().toLocaleDateString()}</div>
          <div><strong>EMIS No:</strong> ${student.emis}</div>
          <div><strong>Aadhar ID:</strong> ${student.aadhar}</div>
        </div>
      </div>

      <hr/>

      <div class="section">
        <h2>1. Student Profile & Credentials</h2>
        <table class="data-table">
          <tr><th>Student Name</th><td>${student.name}</td><th>Department</th><td>${student.department}</td></tr>
          <tr><th>Year & Section</th><td>Year ${student.year}, Section ${student.section}</td><th>Email</th><td>${student.email}</td></tr>
          <tr><th>Phone Number</th><td>${student.phone}</td><th>Class Advisor</th><td>${student.mentorName || 'Dr. S. Ramanathan'}</td></tr>
        </table>
      </div>

      <div class="section">
        <h2>2. AI Performance & Risk Assessment</h2>
        <div class="kpi-grid">
          <div class="kpi-box">
            <div class="kpi-label">Predicted Final Score</div>
            <div class="kpi-val text-blue">${student.predictedScore}%</div>
          </div>
          <div class="kpi-box">
            <div class="kpi-label">Risk Level</div>
            <div class="kpi-val ${student.riskLevel === 'HIGH' ? 'text-red' : student.riskLevel === 'MEDIUM' ? 'text-amber' : 'text-green'}">${student.riskLevel} RISK</div>
          </div>
          <div class="kpi-box">
            <div class="kpi-label">Attendance Percentage</div>
            <div class="kpi-val">${student.attendance}%</div>
          </div>
          <div class="kpi-box">
            <div class="kpi-label">Assignment Completion</div>
            <div class="kpi-val">${student.assignmentCompletion}%</div>
          </div>
        </div>
      </div>

      <div class="section">
        <h2>3. Subject Performance Breakdown</h2>
        <table class="list-table">
          <thead>
            <tr><th>Code</th><th>Subject Name</th><th>Current Score</th><th>Attendance</th><th>Grade</th></tr>
          </thead>
          <tbody>
            ${student.subjects.map((sub) => `
              <tr>
                <td>${sub.code}</td>
                <td><strong>${sub.name}</strong></td>
                <td>${sub.score}%</td>
                <td>${sub.attendance}%</td>
                <td>${sub.grade}</td>
              </tr>
            `).join('')}
          </tbody>
        </table>
      </div>

      <div class="section">
        <h2>4. Explainable AI Risk Signals</h2>
        <ul>
          ${student.riskFactors.map((rf) => `
            <li><strong>[${rf.impact}]</strong> ${rf.factor}: ${rf.description}</li>
          `).join('')}
        </ul>
      </div>

      <div class="footer">
        <div>Official Seal • Generated via Kalvikkan AI Early Intervention Platform</div>
        <div>Page 1 of 1</div>
      </div>
    `;
  } else if (role === 'faculty') {
    title = 'Faculty Class Risk & Intervention Summary Report';
    const highRisk = allStudents.filter((s) => s.riskLevel === 'HIGH');
    const mediumRisk = allStudents.filter((s) => s.riskLevel === 'MEDIUM');

    bodyContent = `
      <div class="header">
        <div class="logo-box">
          <div class="logo-title">கல்விக்கண் (KALVIKKAN)</div>
          <div class="logo-sub">Faculty Class-wide Academic Risk Summary Report</div>
          <div class="tagline">கற்றல் | முன்னேற்றம் | சிறந்த எதிர்காலம்</div>
        </div>
        <div class="report-meta">
          <div><strong>Generated By:</strong> Dr. S. Ramanathan (Faculty Advisor)</div>
          <div><strong>Date:</strong> ${new Date().toLocaleDateString()}</div>
          <div><strong>Cohort Size:</strong> ${allStudents.length} Students</div>
        </div>
      </div>

      <hr/>

      <div class="section">
        <h2>1. Institutional Cohort Overview</h2>
        <div class="kpi-grid">
          <div class="kpi-box">
            <div class="kpi-label">Total Enrolled</div>
            <div class="kpi-val">${allStudents.length}</div>
          </div>
          <div class="kpi-box">
            <div class="kpi-label">High Risk Students</div>
            <div class="kpi-val text-red">${highRisk.length}</div>
          </div>
          <div class="kpi-box">
            <div class="kpi-label">Medium Risk Students</div>
            <div class="kpi-val text-amber">${mediumRisk.length}</div>
          </div>
          <div class="kpi-box">
            <div class="kpi-label">Active Interventions</div>
            <div class="kpi-val text-blue">${interventions.length}</div>
          </div>
        </div>
      </div>

      <div class="section">
        <h2>2. High Academic Risk Roster (${highRisk.length} Students)</h2>
        <table class="list-table">
          <thead>
            <tr><th>Student Name</th><th>EMIS</th><th>Department</th><th>Score</th><th>Attendance</th><th>Primary Issue</th></tr>
          </thead>
          <tbody>
            ${highRisk.map((st) => `
              <tr>
                <td><strong>${st.name}</strong></td>
                <td>${st.emis}</td>
                <td>${st.department}</td>
                <td class="text-red"><strong>${st.predictedScore}%</strong></td>
                <td>${st.attendance}%</td>
                <td>${st.riskFactors[0]?.factor || 'Marks decline'}</td>
              </tr>
            `).join('')}
          </tbody>
        </table>
      </div>

      <div class="section">
        <h2>3. Active Intervention Workflows</h2>
        <table class="list-table">
          <thead>
            <tr><th>Student</th><th>Strategy</th><th>Status</th><th>Faculty Assigned</th></tr>
          </thead>
          <tbody>
            ${interventions.map((item) => `
              <tr>
                <td>${item.studentName}</td>
                <td>${item.recommendedIntervention}</td>
                <td><strong>${item.status}</strong></td>
                <td>${item.assignedFaculty}</td>
              </tr>
            `).join('')}
          </tbody>
        </table>
      </div>
    `;
  } else {
    // Admin Report
    title = 'Institutional Governance & Department Performance Report';
    bodyContent = `
      <div class="header">
        <div class="logo-box">
          <div class="logo-title">கல்விக்கண் (KALVIKKAN)</div>
          <div class="logo-sub">Administrator Institutional Performance Report</div>
          <div class="tagline">கற்றல் | முன்னேற்றம் | சிறந்த எதிர்காலம்</div>
        </div>
        <div class="report-meta">
          <div><strong>System Admin:</strong> Kalvikkan Governance</div>
          <div><strong>Date:</strong> ${new Date().toLocaleDateString()}</div>
        </div>
      </div>

      <hr/>

      <div class="section">
        <h2>1. Department Academic Breakdown</h2>
        <table class="list-table">
          <thead>
            <tr><th>Department</th><th>Students</th><th>Avg Performance</th><th>High Risk Count</th></tr>
          </thead>
          <tbody>
            <tr><td>AI & DS</td><td>22</td><td>74.2%</td><td class="text-red">4</td></tr>
            <tr><td>CSE</td><td>15</td><td>78.5%</td><td class="text-red">2</td></tr>
            <tr><td>ECE</td><td>8</td><td>69.8%</td><td class="text-red">3</td></tr>
            <tr><td>IT</td><td>6</td><td>71.4%</td><td class="text-red">1</td></tr>
            <tr><td>MECH</td><td>5</td><td>62.1%</td><td class="text-red">4</td></tr>
            <tr><td>EEE</td><td>3</td><td>65.4%</td><td class="text-red">2</td></tr>
          </tbody>
        </table>
      </div>
    `;
  }

  printWindow.document.write(`
    <!DOCTYPE html>
    <html>
      <head>
        <title>${title}</title>
        <style>
          body { font-family: system-ui, -apple-system, sans-serif; padding: 30px; color: #0f172a; line-height: 1.5; }
          .header { display: flex; justify-content: space-between; align-items: flex-start; margin-bottom: 20px; }
          .logo-title { font-size: 24px; font-weight: 900; color: #1d4ed8; }
          .logo-sub { font-size: 12px; font-weight: 700; color: #475569; }
          .tagline { font-size: 11px; color: #10b981; font-weight: 600; margin-top: 4px; }
          .report-meta { text-align: right; font-size: 12px; color: #64748b; }
          hr { border: none; border-top: 2px solid #e2e8f0; margin: 20px 0; }
          .section { margin-bottom: 25px; }
          h2 { font-size: 15px; font-weight: 800; text-transform: uppercase; color: #1e293b; border-bottom: 1px solid #cbd5e1; padding-bottom: 5px; }
          .data-table, .list-table { width: 100%; border-collapse: collapse; margin-top: 10px; font-size: 12px; }
          .data-table th, .list-table th { background: #f1f5f9; padding: 8px 12px; text-align: left; font-weight: 700; border: 1px solid #cbd5e1; }
          .data-table td, .list-table td { padding: 8px 12px; border: 1px solid #e2e8f0; }
          .kpi-grid { display: grid; grid-template-columns: repeat(4, 1fr); gap: 12px; margin-top: 10px; }
          .kpi-box { background: #f8fafc; border: 1px solid #e2e8f0; padding: 12px; border-radius: 8px; text-align: center; }
          .kpi-label { font-size: 10px; font-weight: 700; text-transform: uppercase; color: #64748b; }
          .kpi-val { font-size: 20px; font-weight: 900; margin-top: 4px; }
          .text-red { color: #ef4444; }
          .text-amber { color: #f59e0b; }
          .text-green { color: #10b981; }
          .text-blue { color: #2563eb; }
          ul { font-size: 12px; padding-left: 20px; }
          li { margin-bottom: 6px; }
          .footer { margin-top: 40px; border-top: 1px solid #e2e8f0; pt-10px; font-size: 11px; color: #94a3b8; display: flex; justify-content: space-between; }
          @media print {
            body { padding: 0; }
          }
        </style>
      </head>
      <body>
        ${bodyContent}
        <script>
          window.onload = function() {
            window.print();
          };
        </script>
      </body>
    </html>
  `);
  printWindow.document.close();
}
